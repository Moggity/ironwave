#!/usr/bin/env node
/* ============================================================
   IRONWAVE — scripts/build-icons.js
   Turns the source SVGs in app/icons/ui/ into app/icons.js, the
   one file the app loads. There is no build step at runtime: run
   this by hand after adding or changing an icon, and commit the
   result.

     node scripts/build-icons.js          write app/icons.js
     node scripts/build-icons.js --check  exit 1 if it is out of date

   Source rules (see app/icons/ui/README.md): one 24 x 24 viewBox,
   one colour. Every colour becomes currentColor so CSS tints the
   icon; the outer <svg>, clip-path wrappers and <defs> are dropped.
   The icon name is the file name in lower case with "_" as "-"
   (Drag_grip.svg -> drag-grip). Sub-folders only organise sources.
   ============================================================ */
'use strict';
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', 'app', 'icons', 'ui');
const OUT = path.join(__dirname, '..', 'app', 'icons.js');
const VIEWBOX = '0 0 24 24';

function svgFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
    .flatMap(d => {
      const p = path.join(dir, d.name);
      if (d.isDirectory()) return svgFiles(p);
      return d.name.toLowerCase().endsWith('.svg') ? [p] : [];
    });
}

function iconName(file) {
  return path.basename(file).replace(/\.svg$/i, '').toLowerCase().replace(/_/g, '-');
}

function iconBody(file) {
  const src = fs.readFileSync(file, 'utf8');
  const rel = path.relative(SRC, file);
  const open = src.match(/<svg\b[^>]*>/);
  if (!open) throw new Error(`${rel}: no <svg> element`);
  const vb = (open[0].match(/viewBox="([^"]*)"/) || [])[1];
  if (vb !== VIEWBOX) throw new Error(`${rel}: viewBox must be "${VIEWBOX}", found "${vb}"`);
  let body = src
    .replace(/<\?xml[\s\S]*?\?>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<defs>[\s\S]*?<\/defs>/g, '')
    .replace(/<svg\b[^>]*>/, '').replace(/<\/svg>/, '')
    .replace(/<g\b[^>]*>/g, '').replace(/<\/g>/g, '')
    .replace(/\b(stroke|fill)="(?!none")[^"]*"/g, '$1="currentColor"')
    .replace(/\s*\r?\n\s*/g, '')
    .trim();
  if (/<(image|text|style|script|mask|filter|use)\b/i.test(body) || /\son\w+=/i.test(body)) {
    throw new Error(`${rel}: only plain shapes are supported`);
  }
  if (body.includes("'") || body.includes('\\')) throw new Error(`${rel}: unexpected quote or backslash`);
  return body;
}

function build() {
  const seen = new Map();
  for (const file of svgFiles(SRC)) {
    const name = iconName(file);
    if (seen.has(name)) throw new Error(`duplicate icon name "${name}"`);
    seen.set(name, iconBody(file));
  }
  const names = [...seen.keys()].sort();
  const lines = names.map(n => `  '${n}': '${seen.get(n)}',`);
  return [
    '/* IRONWAVE UI icons. GENERATED by scripts/build-icons.js from app/icons/ui/.',
    '   Do not edit by hand: change the source SVG and run the script again. */',
    `const ICON_VIEWBOX = '${VIEWBOX}';`,
    'const ICONS = {',
    ...lines,
    '};',
    '',
  ].join('\n');
}

if (require.main === module) {
  const out = build();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (cur !== out) { console.error('app/icons.js is out of date. Run: node scripts/build-icons.js'); process.exit(1); }
    console.log('app/icons.js is up to date');
  } else {
    fs.writeFileSync(OUT, out);
    console.log(`wrote app/icons.js (${(out.match(/^  '/gm) || []).length} icons)`);
  }
}

module.exports = { build, OUT };
